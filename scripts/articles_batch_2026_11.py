def _wrap(draw, text, font, width):
    # split on plain spaces only, so «15 000 ₸» joined with no-break spaces stays on one line
    words, lines, cur = text.split(' '), [], ''
    for w in words:
        t = (cur + ' ' + w).strip(' ')
        if draw.textlength(t, font=font) <= width:
            cur = t
        else:
            lines.append(cur)
            cur = w
    lines.append(cur)
    return lines


