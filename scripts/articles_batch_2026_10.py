def wrap(draw, text, font, width):
    words, lines, cur = text.split(), [], ''
    for w in words:
        t = (cur + ' ' + w).strip()
        if draw.textlength(t, font=font) <= width:
            cur = t
        else:
            lines.append(cur)
            cur = w
    lines.append(cur)
    return lines


def cover(a, out):
    W, H = 1200, 630
    bg = Image.open(os.path.join(SITE, 'assets/img', a['photo'] + '.webp')).convert('RGB')
    scale = max(W / bg.width, H / bg.height)
    bg = bg.resize((int(bg.width * scale) + 1, int(bg.height * scale) + 1), Image.LANCZOS)
    left, top = (bg.width - W) // 2, (bg.height - H) // 2
    bg = bg.crop((left, top, left + W, top + H)).filter(ImageFilter.GaussianBlur(1.2))
    # dark brand gradient from the left so the headline always reads
    shade = Image.new('RGB', (W, H), (6, 40, 56))
    mask = Image.linear_gradient('L').rotate(90).resize((W, H))
    mask = mask.point(lambda v: int(130 + v * 0.45))
    img = Image.composite(shade, bg, mask)
    d = ImageDraw.Draw(img)
    tag_font = ImageFont.truetype(FONT_SEMI, 28)
    tw = d.textlength(a['tag'].upper(), font=tag_font)
    d.rounded_rectangle((64, 64, 64 + tw + 40, 64 + 52), radius=14, fill=(224, 111, 0))
    d.text((84, 74), a['tag'].upper(), font=tag_font, fill='white')
    size = 64
    while True:
        f = ImageFont.truetype(FONT_BOLD, size)
        lines = wrap(d, a['cover_title'], f, 860)
        if len(lines) <= 4 or size <= 44:
            break
        size -= 4
    y = 150
    for line in lines:
        d.text((64, y), line, font=f, fill='white')
        y += int(size * 1.15)
    foot = ImageFont.truetype(FONT_SEMI, 26)
    d.text((64, H - 70), 'Казахстан-Мед Дез · dezservis.kz', font=foot, fill=(214, 236, 244))
    img.save(out, 'WEBP', quality=82, method=6)


